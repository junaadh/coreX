//! Frontend macro-expansion engine.
//!
//! This module provides the fixed-point expansion loop and AST traversal
//! infrastructure. `rule` clause execution is implemented via a temporary
//! string-render/reparse bridge; `reflect` execution is implemented via
//! template-based code generation.
//!
//! # Provenance Tracking
//!
//! This module implements a **pre-desugar provenance bridge** - a minimal
//! provenance model that preserves origin information through macro expansion
//! before a full AST → HIR lowering exists. This provenance tracking enables:
//!
//! - **Diagnostics**: Error messages point to macro call sites, not expanded code
//! - **Tooling**: LSP go-to-definition, hover, and other features work in expanded code
//! - **Debugging**: Understanding how generated code maps to source
//! - **Future HIR**: Foundation for AST → HIR lowering with source origins
//!
//! ## Provenance Model
//!
//! The provenance model uses three main types:
//!
//! - **`Provenance`**: Enum tracking the origin of syntax nodes
//!   - `DirectSource`: Code directly from source file
//!   - `ExpandedFrom`: Generated by macro expansion (tracks macro name, call site, definition)
//!   - `SyntheticFor`: Compiler-generated code (e.g., hygiene renames)
//!
//! - **`ProvenanceMap`**: Span-based mapping from expanded AST nodes to their provenance
//!   - Uses BTreeMap for deterministic iteration
//!   - Allows lookup by span or byte offset
//!   - File-scoped to prevent ambiguity
//!
//! - **`ExpandedFile`**: Extended parsed unit with provenance tracking
//!   - Contains the expanded AST
//!   - Includes provenance map for all expanded nodes
//!   - Preserves diagnostics from expansion
//!
//! ## Provenance Flow
//!
//! 1. **Macro Expansion**: When a macro is expanded, we record:
//!    ```text
//!    Provenance::ExpandedFrom {
//!        macro_name: "macro_name",
//!        call_site_file: FileId,
//!        call_site_span: Span,        // Where @macro(...) was invoked
//!        definition_span: Option<Span>, // Where in macro definition
//!    }
//!    ```
//!
//! 2. **Hygiene Renaming**: When identifiers are renamed for hygiene:
//!    ```text
//!    Provenance::SyntheticFor {
//!        purpose: SynthesisPurpose::HygieneRename,
//!        related_span: Some((file_id, original_span)),
//!    }
//!    ```
//!
//! 3. **Root Spans**: Expanded expressions get the call-site span as their root span
//!    - This ensures errors point to where the macro was invoked
//!    - Child nodes may have different spans from the template
//!
//! ## Usage Example
//!
//! ```ignore
//! // Expand a file with macros
//! let expanded = expand_file(&db, &parsed, &macros, options)?;
//!
//! // Later, when reporting an error at a span:
//! if let Some(prov) = expanded.provenance_map.get(error_span) {
//!     match prov {
//!         Provenance::ExpandedFrom { call_site_span, .. } => {
//!             // Report error at macro call site instead of expanded code
//!             report_error_at(*call_site_span);
//!         }
//!         Provenance::DirectSource { span, .. } => {
//!             // Report error at original source location
//!             report_error_at(*span);
//!         }
//!         _ => {}
//!     }
//! }
//! ```
//!
//! ## Future AST → HIR Lowering
//!
//! This provenance model is designed to be the foundation for future HIR lowering:
//!
//! - The provenance map will be used to construct HIR nodes with origin information
//! - Desugaring passes can preserve provenance through transformations
//! - Tooling can trace HIR nodes back to their source origins
//!
//! ## V1 Provenance Bridge
//!
//! The current implementation is a "v1 bridge" - a minimal model that works
//! with the existing AST without requiring node-level provenance attachment.
//! Future versions may:
//!
//! - Attach provenance directly to AST nodes
//! - Track provenance through desugaring passes
//! - Support more granular origin tracking
//!
//! # Macro Expansion
//!
//! ## Rule Clauses
//!
//! Rule clauses match patterns against token streams and generate output via
//! template substitution with identifier hygiene.
//!
//! ## Reflect Clauses
//!
//! Reflect clauses match against AST items and generate output via template-based
//! code generation with reflection hooks.
//!
//! # Supported Macro Surface
//!
//! ## Expression Macros (Rule Clauses)
//!
//! **Call-style**: `@macro(arg1, arg2)` - Expands expressions
//! **Block-style**: `@macro { tokens }` - Expands token blocks
//!
//! ## Item Macros (Reflect Clauses)
//!
//! **Attached**: `@macro struct Foo { ... }` - Reflects and transforms items
//!
//! ## Unsupported Forms
//!
//! The following forms are declared in the AST but **not implemented**:
//! - `rule(Item)` - Attached rule macros (use `reflect(Item)` instead)
//! - `reflect(Expr)` - Expression reflection (use `rule(Expr)` instead)
//! - `reflect(Tokens)` - Block reflection (use `rule(Tokens)` instead)
//! - `rule(Stmt)`, `rule(Block)`, `rule(Type)`, `rule(Pattern)` - Not implemented
//! - `MacroArgs` - Declared but not implemented
//!
//! ## Expansion Contract
//!
//! ### Current State (v1)
//!
//! - **Input**: `ParsedFile` (AST + file_id + diagnostics)
//! - **Output**: `ExpandedFile` (AST + file_id + diagnostics + provenance)
//! - **Method**: Fixed-point iteration (expand until stable)
//! - **Tracking**: Provenance map for error reporting
//! - **Hygiene**: Basic identifier hygiene via rendering
//! - **No semantic ids/types yet**
//! - **No desugaring yet**
//!
//! ### Future Desugaring Bridge
//!
//! ```text
//! Parsed AST → Macro Expansion → Desugaring → HIR
//!             (current v1)      (future)     (future)
//! ```
//!

