fn expand_file_with_hook(
    db: &crate::frontend::source::SourceDb,
    parsed: &ParsedFile,
    macros: &MacroTable,
    options: ExpansionOptions,
    mut hook: impl FnMut(
        &Spanned<Expr>,
        &MacroTable,
        &crate::frontend::source::SourceDb,
        FileId,
        &mut ProvenanceMap,
    ) -> MacroExpansionResult,
) -> ExpandedFile {
    let mut ast = parsed.ast.clone();
    let mut diagnostics = parsed.diagnostics.clone();
    let mut provenance_map = ProvenanceMap::new(parsed.file_id);

    if options.recursion_limit == 0 {
        diagnostics.push(recursion_limit_diagnostic(
            parsed.file_id,
            options.recursion_limit,
            first_file_span(&ast),
        ));
        return ExpandedFile {
            file_id: parsed.file_id,
            ast,
            diagnostics,
            provenance_map,
        };
    }

    for iteration in 0..options.recursion_limit {
        let mut pass = ExpansionPass {
            file_id: parsed.file_id,
            db,
            macros,
            changed: false,
            last_expansion_span: None,
            diagnostics: Vec::new(),
            hook: &mut hook,
            provenance_map: &mut provenance_map,
        };
        expand_file_once(&mut ast, &mut pass);
        diagnostics.extend(pass.diagnostics);

        if !pass.changed {
            return ExpandedFile {
                file_id: parsed.file_id,
                ast,
                diagnostics,
                provenance_map,
            };
        }

        if iteration + 1 == options.recursion_limit {
            diagnostics.push(recursion_limit_diagnostic(
                parsed.file_id,
                options.recursion_limit,
                pass.last_expansion_span.or_else(|| first_file_span(&ast)),
            ));
            break;
        }
    }

    ExpandedFile {
        file_id: parsed.file_id,
        ast,
        diagnostics,
        provenance_map,
    }
}

struct ExpansionPass<'a, 'h> {
    file_id: FileId,
    db: &'a crate::frontend::source::SourceDb,
    macros: &'a MacroTable,
    changed: bool,
    last_expansion_span: Option<crate::frontend::ast::Span>,
    diagnostics: Vec<Diagnostic>,
    hook: &'h mut ExpandHook<'h>,
    provenance_map: &'h mut ProvenanceMap,
}

fn expand_file_once(ast: &mut File, pass: &mut ExpansionPass<'_, '_>) {
    let mut index = 0usize;
    while index < ast.items.len() {
        expand_attached_item_if_present(ast, index, pass);
        let item = &mut ast.items[index];
        expand_item(item, pass);
        index = index.saturating_add(1);
    }
}

fn expand_attached_item_if_present(
    ast: &mut File,
    index: usize,
    pass: &mut ExpansionPass<'_, '_>,
) {
    let Some((macro_name, invocation_span)) =
        item_macro_attribute(&ast.items[index], pass.macros)
    else {
        return;
    };

    let invocation = MacroInvocation::attached(macro_name, invocation_span);
    let selection = match dispatch_macro(pass.macros, &invocation, pass.file_id)
    {
        Ok(selection) => selection,
        Err(diagnostic) => {
            pass.diagnostics.push(diagnostic);
            return;
        }
    };

    match selection.clause.kind {
        MacroClauseKind::Rule => {
            pass.diagnostics.push(
                Diagnostic::error("attached rule macros are not supported")
                    .with_label(DiagnosticLabel::primary(
                        FileSpan::new(pass.file_id, invocation.span),
                        "attached invocation requires a reflect clause",
                    ))
                    .with_note(
                        "rule clauses are only supported for call-style `@macro(...)` \
                         and block-style `@macro{...}` invocations",
                    )
                    .with_help(
                        "change this macro clause from `rule(...)` to `reflect(item: Item)`",
                    ),
            );
        }
        MacroClauseKind::Reflect => {
            let current_item = ast.items[index].clone();
            match execute_reflect_clause(
                MacroInvocationInput::Item(&current_item),
                &invocation,
                selection.definition,
                selection.clause,
                pass.macros,
                pass.db,
                pass.file_id,
                pass.provenance_map,
            ) {
                Ok(ExpandedAstFragment::Item(expanded_item)) => {
                    pass.changed = true;
                    pass.last_expansion_span = Some(invocation.span);
                    ast.items[index] = expanded_item;
                }
                Ok(ExpandedAstFragment::Expr(_)) => {
                    pass.diagnostics.push(
                        Diagnostic::error(
                            "attached reflect macro produced expression output",
                        )
                        .with_label(
                            DiagnosticLabel::primary(
                                FileSpan::new(pass.file_id, invocation.span),
                                "attached macro expansion must produce an item",
                            ),
                        ),
                    );
                }
                Err(diagnostic) => pass.diagnostics.push(diagnostic),
            }
        }
    }
}

fn item_macro_attribute(
    item: &Spanned<Item>,
    macros: &MacroTable,
) -> Option<(String, crate::frontend::ast::Span)> {
    let attributes = match &item.node {
        Item::Struct(decl) => Some(&decl.node.attributes),
        Item::Enum(decl) => Some(&decl.node.attributes),
        Item::Impl(decl) => Some(&decl.node.attributes),
        Item::Protocol(decl) => Some(&decl.node.attributes),
        Item::Function(decl) => Some(&decl.node.attributes),
        Item::ExternBlock(decl) => Some(&decl.node.attributes),
        Item::Macro(decl) => Some(&decl.node.attributes),
        Item::Use(_) | Item::Scope(_) => None,
    }?;

    attributes.iter().find_map(|attribute| {
        if macros.get(&attribute.node.name).is_some() {
            Some((attribute.node.name.clone(), attribute.span))
        } else {
            None
        }
    })
}

fn expand_item(item: &mut Spanned<Item>, pass: &mut ExpansionPass<'_, '_>) {
    match &mut item.node {
        Item::Function(function_decl) => {
            expand_function_decl(&mut function_decl.node, pass);
        }
        Item::Struct(struct_decl) => {
            expand_struct_decl(&mut struct_decl.node, pass);
        }
        Item::Enum(enum_decl) => {
            expand_enum_decl(&mut enum_decl.node, pass);
        }
        Item::Impl(impl_decl) => {
            expand_impl_decl(&mut impl_decl.node, pass);
        }
        Item::Protocol(protocol_decl) => {
            expand_protocol_decl(&mut protocol_decl.node, pass);
        }
        Item::Use(_)
        | Item::Scope(_)
        | Item::ExternBlock(_)
        | Item::Macro(_) => {}
    }
}

fn expand_function_decl(
    function_decl: &mut FunctionDecl,
    pass: &mut ExpansionPass<'_, '_>,
) {
    expand_block(&mut function_decl.body, pass);
}

fn expand_init_decl(
    init_decl: &mut InitDecl,
    pass: &mut ExpansionPass<'_, '_>,
) {
    expand_block(&mut init_decl.body, pass);
}

fn expand_struct_decl(
    struct_decl: &mut StructDecl,
    pass: &mut ExpansionPass<'_, '_>,
) {
    for member in &mut struct_decl.members {
        match &mut member.node {
            StructMember::Init(init_decl) => {
                expand_init_decl(&mut init_decl.node, pass);
            }
            StructMember::Function(function_decl) => {
                expand_function_decl(&mut function_decl.node, pass);
            }
            StructMember::Field(_) => {}
        }
    }
}

fn expand_enum_decl(
    enum_decl: &mut EnumDecl,
    pass: &mut ExpansionPass<'_, '_>,
) {
    for member in &mut enum_decl.members {
        match &mut member.node {
            EnumMember::Init(init_decl) => {
                expand_init_decl(&mut init_decl.node, pass);
            }
            EnumMember::Function(function_decl) => {
                expand_function_decl(&mut function_decl.node, pass);
            }
            EnumMember::Case(_) => {}
        }
    }
}

fn expand_impl_decl(
    impl_decl: &mut ImplDecl,
    pass: &mut ExpansionPass<'_, '_>,
) {
    for member in &mut impl_decl.members {
        match &mut member.node {
            ImplMember::Init(init_decl) => {
                expand_init_decl(&mut init_decl.node, pass);
            }
            ImplMember::Function(function_decl) => {
                expand_function_decl(&mut function_decl.node, pass);
            }
        }
    }
}

fn expand_protocol_decl(
    protocol_decl: &mut ProtocolDecl,
    pass: &mut ExpansionPass<'_, '_>,
) {
    for member in &mut protocol_decl.members {
        match &mut member.node {
            ProtocolMember::Function(function_member) => {
                if let Some(default_body) =
                    function_member.node.default_body.as_mut()
                {
                    expand_block(default_body, pass);
                }
            }
            ProtocolMember::Initializer(init_member) => {
                if let Some(default_body) =
                    init_member.node.default_body.as_mut()
                {
                    expand_block(default_body, pass);
                }
            }
            ProtocolMember::AssociatedType(_) | ProtocolMember::Property(_) => {
            }
        }
    }
}

fn expand_block(block: &mut Block, pass: &mut ExpansionPass<'_, '_>) {
    for statement in &mut block.statements {
        expand_stmt(statement, pass);
    }
    if let Some(tail_expr) = block.tail_expr.as_mut() {
        expand_expr(tail_expr, pass);
    }
}

fn expand_stmt(stmt: &mut Spanned<Stmt>, pass: &mut ExpansionPass<'_, '_>) {
    match &mut stmt.node {
        Stmt::If(if_stmt) => expand_if_stmt(&mut if_stmt.node, pass),
        Stmt::Let(let_stmt) => {
            if let Some(value) = let_stmt.node.value.as_mut() {
                expand_expr(value, pass);
            }
        }
        Stmt::Var(var_stmt) => {
            if let Some(value) = var_stmt.node.value.as_mut() {
                expand_expr(value, pass);
            }
        }
        Stmt::Expr { expr, .. } => expand_expr(expr, pass),
        Stmt::Guard(guard_stmt) => {
            expand_clause_list(&mut guard_stmt.node.clauses, pass);
            expand_block(&mut guard_stmt.node.else_block, pass);
        }
        Stmt::While(while_stmt) => {
            expand_clause_list(&mut while_stmt.node.clauses, pass);
            expand_block(&mut while_stmt.node.body, pass);
        }
        Stmt::For(for_stmt) => {
            expand_expr(&mut for_stmt.node.iterator, pass);
            expand_block(&mut for_stmt.node.body, pass);
        }
        Stmt::Return(expr) => {
            if let Some(expr) = expr.as_mut() {
                expand_expr(expr, pass);
            }
        }
        Stmt::Break | Stmt::Continue => {}
    }
}

fn expand_if_stmt(if_stmt: &mut IfStmt, pass: &mut ExpansionPass<'_, '_>) {
    expand_clause_list(&mut if_stmt.clauses, pass);
    expand_block(&mut if_stmt.then_branch, pass);
    if let Some(else_branch) = if_stmt.else_branch.as_mut() {
        match else_branch {
            IfStmtElse::If(else_if) => expand_if_stmt(&mut else_if.node, pass),
            IfStmtElse::Block(block) => expand_block(block, pass),
        }
    }
}

fn expand_clause_list(
    clauses: &mut ClauseList,
    pass: &mut ExpansionPass<'_, '_>,
) {
    for clause in &mut clauses.clauses {
        match &mut clause.node {
            Clause::Expr(expr) => expand_expr(expr, pass),
            Clause::LetBinding(binding) | Clause::VarBinding(binding) => {
                expand_expr(&mut binding.value, pass);
            }
        }
    }
}

fn expand_expr(expr: &mut Spanned<Expr>, pass: &mut ExpansionPass<'_, '_>) {
    let replacement = if matches!(&expr.node, Expr::Macro { .. }) {
        let result = (pass.hook)(expr, pass.macros, pass.db, pass.file_id, pass.provenance_map);
        if !result.diagnostics.is_empty() {
            pass.diagnostics.extend(result.diagnostics);
        }
        result.replacement
    } else {
        None
    };

    if let Some(expanded) = replacement {
        pass.changed = true;
        pass.last_expansion_span = Some(expr.span);
        *expr = expanded;
    }

    match &mut expr.node {
        Expr::StringLiteral(literal) => {
            for part in &mut literal.parts {
                if let crate::frontend::ast::StringPart::Interpolation(inner) =
                    part
                {
                    expand_expr(inner, pass);
                }
            }
        }
        Expr::Grouped(inner)
        | Expr::Try { expr: inner }
        | Expr::ForceUnwrap { expr: inner }
        | Expr::Spread { expr: inner }
        | Expr::Unary { expr: inner, .. } => {
            expand_expr(inner, pass);
        }
        Expr::QualifiedMember { qualifier, .. } => {
            expand_expr(qualifier, pass);
        }
        Expr::ArrayLiteral(elements) => {
            for element in elements {
                match element {
                    crate::frontend::ast::ArrayElement::Expr(inner)
                    | crate::frontend::ast::ArrayElement::Spread(inner) => {
                        expand_expr(inner, pass);
                    }
                }
            }
        }
        Expr::StructLiteral { fields, .. } => {
            for field in fields {
                match field {
                    crate::frontend::ast::StructLiteralField::Named {
                        value,
                        ..
                    }
                    | crate::frontend::ast::StructLiteralField::Spread {
                        value,
                    } => expand_expr(value, pass),
                    crate::frontend::ast::StructLiteralField::Shorthand {
                        ..
                    } => {}
                }
            }
        }
        Expr::Block(block) | Expr::UnsafeBlock(block) => {
            expand_block(block, pass);
        }
        Expr::If {
            clauses,
            then_branch,
            else_branch,
        } => {
            expand_clause_list(clauses, pass);
            expand_block(then_branch, pass);
            if let Some(else_branch) = else_branch.as_mut() {
                expand_expr(else_branch, pass);
            }
        }
        Expr::Match { subject, arms } => {
            expand_expr(subject, pass);
            for arm in arms {
                match &mut arm.node.body {
                    MatchArmBody::Expr(inner) => expand_expr(inner, pass),
                    MatchArmBody::Block(block) => expand_block(block, pass),
                }
            }
        }
        Expr::Closure { body, .. } => {
            expand_block(body, pass);
        }
        Expr::Macro { args, .. } => match args {
            crate::frontend::ast::MacroExprArgs::Paren(args) => {
                for arg in args {
                    expand_expr(&mut arg.value, pass);
                }
            }
            crate::frontend::ast::MacroExprArgs::Braced(_) => {}
        },
        Expr::Ternary {
            condition,
            then_expr,
            else_expr,
        } => {
            expand_expr(condition, pass);
            expand_expr(then_expr, pass);
            expand_expr(else_expr, pass);
        }
        Expr::Binary { lhs, rhs, .. } => {
            expand_expr(lhs, pass);
            expand_expr(rhs, pass);
        }
        Expr::Assignment { target, value, .. } => {
            expand_expr(target, pass);
            expand_expr(value, pass);
        }
        Expr::MemberAccess { base, .. }
        | Expr::OptionalMemberAccess { base, .. }
        | Expr::NamespaceAccess { base, .. } => {
            expand_expr(base, pass);
        }
        Expr::Call {
            callee,
            args,
            trailing_closure,
        } => {
            expand_expr(callee, pass);
            for arg in args {
                expand_expr(&mut arg.value, pass);
            }
            if let Some(trailing) = trailing_closure.as_mut() {
                expand_expr(trailing, pass);
            }
        }
        Expr::Index { base, index } | Expr::OptionalIndex { base, index } => {
            expand_expr(base, pass);
            expand_expr(index, pass);
        }
        Expr::Cast {
            expr: inner, ty, ..
        } => {
            expand_expr(inner, pass);
            expand_type(&mut ty.node, pass);
        }
        Expr::Range { start, end, .. } => {
            if let Some(start) = start.as_mut() {
                expand_expr(start, pass);
            }
            if let Some(end) = end.as_mut() {
                expand_expr(end, pass);
            }
        }
        Expr::IntegerLiteral(_)
        | Expr::FloatLiteral(_)
        | Expr::CharLiteral(_)
        | Expr::BooleanLiteral(_)
        | Expr::Identifier(_)
        | Expr::SelfValue
        | Expr::SelfType
        | Expr::ShorthandMember { .. } => {}
    }
}

fn expand_type(ty: &mut Type, pass: &mut ExpansionPass<'_, '_>) {
    match ty {
        Type::GenericApplication { base, args } => {
            expand_type(&mut base.node, pass);
            for arg in args {
                expand_type(&mut arg.node, pass);
            }
        }
        Type::Reference(inner)
        | Type::MutableReference(inner)
        | Type::ConstPointer(inner)
        | Type::MutablePointer(inner)
        | Type::Array(inner)
        | Type::Optional(inner)
        | Type::Grouped(inner) => {
            expand_type(&mut inner.node, pass);
        }
        Type::Result { ok, err } => {
            expand_type(&mut ok.node, pass);
            expand_type(&mut err.node, pass);
        }
        Type::Named { .. } | Type::SelfType => {}
    }
}

fn recursion_limit_diagnostic(
    file_id: FileId,
    recursion_limit: usize,
    span: Option<crate::frontend::ast::Span>,
) -> Diagnostic {
    let mut diagnostic = Diagnostic::error(
        "macro expansion recursion limit exceeded",
    )
    .with_note(format!(
        "expansion did not reach a fixed point within {recursion_limit} iteration(s)"
    ))
    .with_help(
        "increase `ExpansionOptions::recursion_limit` or reduce recursive macro expansion",
    );

    if let Some(span) = span {
        diagnostic = diagnostic.with_label(DiagnosticLabel::primary(
            FileSpan::new(file_id, span),
            "expansion kept changing here",
        ));
    }

    diagnostic
}

fn first_file_span(ast: &File) -> Option<crate::frontend::ast::Span> {
    ast.items.first().map(|item| item.span)
}

fn placeholder_expand_macro(
    invocation: &Spanned<Expr>,
    macros: &MacroTable,
    db: &crate::frontend::source::SourceDb,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) -> MacroExpansionResult {
    let Some(dispatch_invocation) = MacroInvocation::from_expr(invocation)
    else {
        return MacroExpansionResult::default();
    };
    let selection = match dispatch_macro(macros, &dispatch_invocation, file_id)
    {
        Ok(selection) => selection,
        Err(diagnostic) => {
            return MacroExpansionResult {
                replacement: None,
                diagnostics: vec![diagnostic],
            };
        }
    };

    match selection.clause.kind {
        MacroClauseKind::Rule => match execute_rule_clause(
            invocation,
            &dispatch_invocation,
            selection.definition,
            selection.clause,
            macros,
            db,
            file_id,
            provenance_map,
        ) {
            Ok(expanded) => MacroExpansionResult {
                replacement: Some(expanded),
                diagnostics: Vec::new(),
            },
            Err(diagnostic) => MacroExpansionResult {
                replacement: None,
                diagnostics: vec![diagnostic],
            },
        },
        MacroClauseKind::Reflect => match execute_reflect_clause(
            MacroInvocationInput::Expr,
            &dispatch_invocation,
            selection.definition,
            selection.clause,
            macros,
            db,
            file_id,
            provenance_map,
        ) {
            Ok(ExpandedAstFragment::Expr(expanded)) => MacroExpansionResult {
                replacement: Some(expanded),
                diagnostics: Vec::new(),
            },
            Ok(ExpandedAstFragment::Item(_)) => MacroExpansionResult {
                replacement: None,
                diagnostics: vec![Diagnostic::error(
                    "expression macro reflect expansion produced item output",
                )
                .with_label(DiagnosticLabel::primary(
                    FileSpan::new(file_id, dispatch_invocation.span),
                    "expression-position macro expansion must produce an expression",
                ))],
            },
            Err(diagnostic) => MacroExpansionResult {
                replacement: None,
                diagnostics: vec![diagnostic],
            },
        },
    }
}

fn execute_rule_clause(
    invocation_expr: &Spanned<Expr>,
    invocation: &MacroInvocation,
    definition: &MacroDefinition,
    clause: &MacroClause,
    macros: &MacroTable,
    db: &crate::frontend::source::SourceDb,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) -> Result<Spanned<Expr>, Diagnostic> {
    let bindings = bind_rule_parameters(
        invocation_expr,
        invocation,
        clause,
        macros,
        db,
        file_id,
    )?;
    let template_source = source_slice_for_macro_body(
        db,
        definition.defining_file_id,
        clause.body.span,
    )
    .ok_or_else(|| {
        Diagnostic::error("macro definition source is unavailable")
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation.span),
                "cannot reconstruct rule template text from SourceDb",
            ))
            .with_note(format!(
                "failed to slice file #{} at {}..{}",
                definition.defining_file_id.raw(),
                clause.body.span.start,
                clause.body.span.end
            ))
    })?;
    let rendered = substitute_template_identifiers(template_source, &bindings);
    let result = parse_expanded_expr(&rendered, invocation.span, file_id, provenance_map)?;

    // Record provenance for the expanded expression
    let provenance = Provenance::ExpandedFrom {
        macro_name: definition.name.clone(),
        call_site_file: file_id,
        call_site_span: invocation.span,
        definition_span: Some(clause.body.span),
    };
    provenance_map.insert(result.span, provenance);

    Ok(result)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ReflectedItemKind {
    Use,
    Scope,
    Struct,
    Enum,
    Impl,
    Protocol,
    Function,
    ExternBlock,
    Macro,
}

impl ReflectedItemKind {
    fn as_str(self) -> &'static str {
        match self {
            Self::Use => "Use",
            Self::Scope => "Scope",
            Self::Struct => "Struct",
            Self::Enum => "Enum",
            Self::Impl => "Impl",
            Self::Protocol => "Protocol",
            Self::Function => "Function",
            Self::ExternBlock => "ExternBlock",
            Self::Macro => "Macro",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct ReflectedItem {
    kind: ReflectedItemKind,
    name: Option<String>,
    fields: Vec<String>,
    variants: Vec<String>,
    params: Vec<String>,
}

impl ReflectedItem {
    fn from_item(item: &Spanned<Item>) -> Self {
        match &item.node {
            Item::Use(_) => Self {
                kind: ReflectedItemKind::Use,
                name: None,
                fields: Vec::new(),
                variants: Vec::new(),
                params: Vec::new(),
            },
            Item::Scope(scope) => Self {
                kind: ReflectedItemKind::Scope,
                name: Some(scope.node.name.clone()),
                fields: Vec::new(),
                variants: Vec::new(),
                params: Vec::new(),
            },
            Item::Struct(struct_decl) => Self {
                kind: ReflectedItemKind::Struct,
                name: Some(struct_decl.node.name.clone()),
                fields: struct_decl
                    .node
                    .members
                    .iter()
                    .filter_map(|member| match &member.node {
                        StructMember::Field(field) => {
                            Some(field.node.name.clone())
                        }
                        StructMember::Init(_) | StructMember::Function(_) => {
                            None
                        }
                    })
                    .collect(),
                variants: Vec::new(),
                params: Vec::new(),
            },
            Item::Enum(enum_decl) => Self {
                kind: ReflectedItemKind::Enum,
                name: Some(enum_decl.node.name.clone()),
                fields: Vec::new(),
                variants: enum_decl
                    .node
                    .members
                    .iter()
                    .filter_map(|member| match &member.node {
                        EnumMember::Case(case_decl) => {
                            Some(case_decl.node.name.clone())
                        }
                        EnumMember::Init(_) | EnumMember::Function(_) => None,
                    })
                    .collect(),
                params: Vec::new(),
            },
            Item::Impl(_) => Self {
                kind: ReflectedItemKind::Impl,
                name: None,
                fields: Vec::new(),
                variants: Vec::new(),
                params: Vec::new(),
            },
            Item::Protocol(protocol_decl) => {
                let mut params = Vec::new();
                for member in &protocol_decl.node.members {
                    match &member.node {
                        ProtocolMember::Function(function_member) => {
                            params.extend(
                                function_member
                                    .node
                                    .params
                                    .iter()
                                    .map(|param| param.node.name.clone()),
                            );
                        }
                        ProtocolMember::Initializer(init_member) => {
                            params.extend(
                                init_member
                                    .node
                                    .params
                                    .iter()
                                    .map(|param| param.node.name.clone()),
                            );
                        }
                        ProtocolMember::AssociatedType(_)
                        | ProtocolMember::Property(_) => {}
                    }
                }

                Self {
                    kind: ReflectedItemKind::Protocol,
                    name: Some(protocol_decl.node.name.clone()),
                    fields: Vec::new(),
                    variants: Vec::new(),
                    params,
                }
            }
            Item::Function(function_decl) => Self {
                kind: ReflectedItemKind::Function,
                name: Some(function_decl.node.name.clone()),
                fields: Vec::new(),
                variants: Vec::new(),
                params: function_decl
                    .node
                    .params
                    .iter()
                    .map(|param| param.node.name.clone())
                    .collect(),
            },
            Item::ExternBlock(_) => Self {
                kind: ReflectedItemKind::ExternBlock,
                name: None,
                fields: Vec::new(),
                variants: Vec::new(),
                params: Vec::new(),
            },
            Item::Macro(macro_decl) => Self {
                kind: ReflectedItemKind::Macro,
                name: Some(macro_decl.node.name.clone()),
                fields: Vec::new(),
                variants: Vec::new(),
                params: Vec::new(),
            },
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum ReflectTemplateNode {
    Text(String),
    Placeholder(String),
    If {
        condition: String,
        body: Vec<ReflectTemplateNode>,
    },
    For {
        binding: String,
        collection: String,
        body: Vec<ReflectTemplateNode>,
    },
}

fn execute_reflect_clause(
    input: MacroInvocationInput<'_>,
    invocation: &MacroInvocation,
    definition: &MacroDefinition,
    clause: &MacroClause,
    _macros: &MacroTable,
    db: &crate::frontend::source::SourceDb,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) -> Result<ExpandedAstFragment, Diagnostic> {
    if clause.input_signature != MacroInputSignature::Item {
        return Err(Diagnostic::error("reflect clauses only support Item input")
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation.span),
                format!(
                    "reflect clause parameter `{}` uses unsupported kind {}",
                    clause.params.first().map(|p| &p.name).unwrap_or(&"<unknown>".to_string()),
                    clause.input_signature.as_str()
                ),
            ))
            .with_note(
                "reflect clauses are only supported for attached item macros \
                 (e.g., `@derive struct Foo { ... }`)",
            )
            .with_help(
                "for expression macros, use a rule clause: \
                 `rule(input: Expr) => { ... }` or `rule(input: Tokens) => { ... }`",
            ));
    }

    let reflected_item = match input {
        MacroInvocationInput::Item(item) => ReflectedItem::from_item(item),
        MacroInvocationInput::Expr => {
            return Err(Diagnostic::error("unsupported reflect input kind")
                .with_label(DiagnosticLabel::primary(
                    FileSpan::new(file_id, invocation.span),
                    "reflect clause expects an attached item invocation",
                )));
        }
    };

    let template_source = source_slice_for_macro_body(
        db,
        definition.defining_file_id,
        clause.body.span,
    )
    .ok_or_else(|| {
        Diagnostic::error("macro definition source is unavailable")
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation.span),
                "cannot reconstruct reflect template text from SourceDb",
            ))
            .with_note(format!(
                "failed to slice file #{} at {}..{}",
                definition.defining_file_id.raw(),
                clause.body.span.start,
                clause.body.span.end
            ))
    })?;

    let rendered = render_reflect_template(template_source, &reflected_item)
        .map_err(|error| {
            Diagnostic::error("reflect template evaluation failed")
                .with_label(DiagnosticLabel::primary(
                    FileSpan::new(file_id, invocation.span),
                    "failed to evaluate reflect template",
                ))
                .with_note(error)
        })?;

    let result = match invocation.shape {
        MacroInvocationShape::Attached => {
            parse_expanded_item(&rendered, invocation.span, file_id, provenance_map)
                .map(ExpandedAstFragment::Item)
        }
        MacroInvocationShape::CallStyle | MacroInvocationShape::BlockStyle => {
            parse_expanded_expr(&rendered, invocation.span, file_id, provenance_map)
                .map(ExpandedAstFragment::Expr)
        }
    };

    // Record provenance for the expanded fragment
    if let Ok(ref fragment) = result {
        let span = match fragment {
            ExpandedAstFragment::Expr(expr) => expr.span,
            ExpandedAstFragment::Item(item) => item.span,
        };
        let provenance = Provenance::ExpandedFrom {
            macro_name: definition.name.clone(),
            call_site_file: file_id,
            call_site_span: invocation.span,
            definition_span: Some(clause.body.span),
        };
        provenance_map.insert(span, provenance);
    }

    result
}

fn render_reflect_template(
    template: &str,
    item: &ReflectedItem,
) -> Result<RenderedTemplate, String> {
    let mut index = 0usize;
    let nodes = parse_reflect_template_nodes(template, &mut index, None)?;
    let env = BTreeMap::new();
    render_reflect_nodes(&nodes, item, &env)
}

fn parse_reflect_template_nodes(
    template: &str,
    index: &mut usize,
    terminator: Option<&str>,
) -> Result<Vec<ReflectTemplateNode>, String> {
    let mut nodes = Vec::new();

    while *index < template.len() {
        let remaining = &template[*index..];
        let Some(open_offset) = remaining.find("{{") else {
            nodes.push(ReflectTemplateNode::Text(remaining.to_string()));
            *index = template.len();
            break;
        };

        if open_offset > 0 {
            nodes.push(ReflectTemplateNode::Text(
                remaining[..open_offset].to_string(),
            ));
            *index += open_offset;
        }

        let tag_start = *index + 2;
        let after_open = &template[tag_start..];
        let Some(close_offset) = after_open.find("}}") else {
            return Err("unterminated template directive".to_string());
        };
        let tag_end = tag_start + close_offset;
        let tag = template[tag_start..tag_end].trim();
        *index = tag_end + 2;

        if let Some(terminator) = terminator
            && tag == terminator
        {
            return Ok(nodes);
        }

        if let Some(condition) = tag.strip_prefix("if ") {
            let body =
                parse_reflect_template_nodes(template, index, Some("endif"))?;
            nodes.push(ReflectTemplateNode::If {
                condition: condition.trim().to_string(),
                body,
            });
            continue;
        }

        if let Some(header) = tag.strip_prefix("for ") {
            let parts = header.split_whitespace().collect::<Vec<_>>();
            if parts.len() != 3 || parts[1] != "in" {
                return Err(format!("invalid for directive: `{tag}`"));
            }
            let body =
                parse_reflect_template_nodes(template, index, Some("endfor"))?;
            nodes.push(ReflectTemplateNode::For {
                binding: parts[0].to_string(),
                collection: parts[2].to_string(),
                body,
            });
            continue;
        }

        if tag == "endif" || tag == "endfor" {
            return Err(format!("unexpected template terminator: `{tag}`"));
        }

        nodes.push(ReflectTemplateNode::Placeholder(tag.to_string()));
    }

    if let Some(terminator) = terminator {
        return Err(format!("missing template terminator: `{terminator}`"));
    }

    Ok(nodes)
}

fn render_reflect_nodes(
    nodes: &[ReflectTemplateNode],
    item: &ReflectedItem,
    env: &BTreeMap<String, MacroBinding>,
) -> Result<RenderedTemplate, String> {
    let mut rendered = RenderedTemplate::default();
    for node in nodes {
        match node {
            ReflectTemplateNode::Text(text) => rendered.source.push_str(text),
            ReflectTemplateNode::Placeholder(path) => {
                let binding = reflect_value(path, item, env)?;
                let start = rendered.source.len();
                rendered.source.push_str(&binding.rendered);
                let end = rendered.source.len();
                if matches!(binding.origin, IdentifierOrigin::FromInput) {
                    rendered.from_input_ranges.push(start..end);
                }
            }
            ReflectTemplateNode::If { condition, body } => {
                if evaluate_reflect_condition(condition, item, env)? {
                    let nested = render_reflect_nodes(body, item, env)?;
                    let base = rendered.source.len();
                    rendered.source.push_str(&nested.source);
                    rendered.from_input_ranges.extend(
                        nested.from_input_ranges.into_iter().map(|range| {
                            (range.start + base)..(range.end + base)
                        }),
                    );
                }
            }
            ReflectTemplateNode::For {
                binding,
                collection,
                body,
            } => {
                let values = reflect_collection(collection, item)?;
                for value in values {
                    let mut next_env = env.clone();
                    next_env.insert(
                        format!("{binding}.name"),
                        MacroBinding {
                            name: format!("{binding}.name"),
                            rendered: value.clone(),
                            origin: IdentifierOrigin::FromInput,
                        },
                    );
                    next_env.insert(
                        binding.clone(),
                        MacroBinding {
                            name: binding.clone(),
                            rendered: value,
                            origin: IdentifierOrigin::FromInput,
                        },
                    );
                    let nested = render_reflect_nodes(body, item, &next_env)?;
                    let base = rendered.source.len();
                    rendered.source.push_str(&nested.source);
                    rendered.from_input_ranges.extend(
                        nested.from_input_ranges.into_iter().map(|range| {
                            (range.start + base)..(range.end + base)
                        }),
                    );
                }
            }
        }
    }
    Ok(rendered)
}

fn evaluate_reflect_condition(
    condition: &str,
    item: &ReflectedItem,
    env: &BTreeMap<String, MacroBinding>,
) -> Result<bool, String> {
    let parts = condition.split_whitespace().collect::<Vec<_>>();
    if parts.len() != 3 {
        return Err(format!("invalid if condition: `{condition}`"));
    }

    let lhs = reflect_value(parts[0], item, env)?.rendered;
    let rhs = parts[2].trim_matches('"').trim_matches('\'').to_string();

    match parts[1] {
        "==" => Ok(lhs == rhs),
        "!=" => Ok(lhs != rhs),
        other => Err(format!(
            "unsupported condition operator `{other}` in `{condition}`"
        )),
    }
}

fn reflect_collection(
    collection: &str,
    item: &ReflectedItem,
) -> Result<Vec<String>, String> {
    match collection {
        "item.fields" => Ok(item.fields.clone()),
        "item.variants" => Ok(item.variants.clone()),
        "item.params" => Ok(item.params.clone()),
        other => Err(format!("unsupported collection `{other}`")),
    }
}

fn reflect_value(
    path: &str,
    item: &ReflectedItem,
    env: &BTreeMap<String, MacroBinding>,
) -> Result<MacroBinding, String> {
    if let Some(value) = env.get(path) {
        return Ok(value.clone());
    }

    match path {
        "item.kind" => Ok(MacroBinding {
            name: path.to_string(),
            rendered: item.kind.as_str().to_string(),
            origin: IdentifierOrigin::FromInput,
        }),
        "item.name" => Ok(MacroBinding {
            name: path.to_string(),
            rendered: item.name.clone().unwrap_or_default(),
            origin: IdentifierOrigin::FromInput,
        }),
        _ => Err(format!("unknown reflect placeholder `{path}`")),
    }
}

fn source_slice_for_macro_body<'a>(
    db: &'a crate::frontend::source::SourceDb,
    file_id: FileId,
    span: crate::frontend::ast::Span,
) -> Option<&'a str> {
    db.file(file_id)?.slice(span)
}

fn bind_rule_parameters(
    invocation_expr: &Spanned<Expr>,
    invocation: &MacroInvocation,
    clause: &MacroClause,
    _macros: &MacroTable,
    db: &crate::frontend::source::SourceDb,
    file_id: FileId,
) -> Result<Vec<MacroBinding>, Diagnostic> {
    if matches!(invocation.shape, MacroInvocationShape::Attached) {
        return Err(Diagnostic::error(
            "attached macro rule execution is not implemented",
        )
        .with_label(DiagnosticLabel::primary_span(FileSpan::new(
            file_id,
            invocation.span,
        ))));
    }

    match (&invocation_expr.node, invocation.shape) {
        (
            Expr::Macro {
                args: MacroExprArgs::Paren(args),
                ..
            },
            MacroInvocationShape::CallStyle,
        ) => {
            if args.len() != clause.params.len() {
                return Err(Diagnostic::error("macro argument count mismatch")
                    .with_label(DiagnosticLabel::primary(
                        FileSpan::new(file_id, invocation.span),
                        format!(
                            "expected {} positional argument(s), found {}",
                            clause.params.len(),
                            args.len()
                        ),
                    )));
            }

            let mut bindings = Vec::with_capacity(clause.params.len());
            for (param, arg) in clause.params.iter().zip(args.iter()) {
                if arg.label.is_some() {
                    return Err(Diagnostic::error(
                        "only positional macro arguments are supported",
                    )
                    .with_label(
                        DiagnosticLabel::primary_span(FileSpan::new(
                            file_id,
                            invocation.span,
                        )),
                    ));
                }

                let rendered = match param.kind {
                    MacroInputSignature::Expr | MacroInputSignature::Tokens => {
                        render_expr_to_source(&arg.value.node)?
                    }
                    _ => {
                        return Err(Diagnostic::error(
                            "unsupported macro parameter kind for rule execution",
                        )
                        .with_label(DiagnosticLabel::primary(
                            FileSpan::new(file_id, invocation.span),
                            format!(
                                "parameter `{}` uses unsupported kind {}",
                                param.name,
                                param.kind.as_str()
                            ),
                        )));
                    }
                };

                bindings.push(MacroBinding {
                    name: param.name.clone(),
                    rendered,
                    origin: IdentifierOrigin::FromInput,
                });
            }

            Ok(bindings)
        }
        (
            Expr::Macro {
                args: MacroExprArgs::Braced(block),
                ..
            },
            MacroInvocationShape::BlockStyle,
        ) => {
            if clause.params.len() != 1 {
                return Err(Diagnostic::error(
                    "block-style macro rules currently require exactly one parameter",
                )
                .with_label(DiagnosticLabel::primary_span(FileSpan::new(
                    file_id,
                    invocation.span,
                ))));
            }

            let param = &clause.params[0];
            match param.kind {
                MacroInputSignature::Tokens | MacroInputSignature::Expr => {
                    let Some(raw) =
                        source_slice_for_macro_body(db, file_id, block.span)
                    else {
                        return Err(Diagnostic::error(
                            "macro invocation source is unavailable",
                        )
                        .with_label(DiagnosticLabel::primary(
                            FileSpan::new(file_id, invocation.span),
                            "cannot reconstruct block argument from SourceDb",
                        ))
                        .with_note(format!(
                            "failed to slice file #{} at {}..{}",
                            file_id.raw(),
                            block.span.start,
                            block.span.end
                        )));
                    };
                    Ok(vec![MacroBinding {
                        name: param.name.clone(),
                        rendered: raw.to_string(),
                        origin: IdentifierOrigin::FromInput,
                    }])
                }
                _ => Err(Diagnostic::error(
                    "unsupported macro parameter kind for block-style rule execution",
                )
                .with_label(DiagnosticLabel::primary(
                    FileSpan::new(file_id, invocation.span),
                    format!(
                        "parameter `{}` uses unsupported kind {}",
                        param.name,
                        param.kind.as_str()
                    ),
                ))),
            }
        }
        _ => Err(Diagnostic::error(
            "macro invocation shape does not match rule execution",
        )
        .with_label(DiagnosticLabel::primary_span(FileSpan::new(
            file_id,
            invocation.span,
        )))),
    }
}

fn substitute_template_identifiers(
    template: &str,
    bindings: &[MacroBinding],
) -> RenderedTemplate {
    let by_name = bindings
        .iter()
        .map(|binding| (binding.name.as_str(), binding))
        .collect::<BTreeMap<_, _>>();

    let mut rendered = RenderedTemplate {
        source: String::with_capacity(template.len()),
        from_input_ranges: Vec::new(),
    };
    let mut index = 0usize;

    while index < template.len() {
        let mut chars = template[index..].chars();
        let Some(ch) = chars.next() else { break };
        let ch_len = ch.len_utf8();

        if is_ident_start(ch) {
            let start = index;
            index += ch_len;
            while index < template.len() {
                let next = template[index..]
                    .chars()
                    .next()
                    .expect("index must remain on char boundary");
                if !is_ident_continue(next) {
                    break;
                }
                index += next.len_utf8();
            }

            let ident = &template[start..index];
            if let Some(binding) = by_name.get(ident) {
                let start = rendered.source.len();
                rendered.source.push_str(&binding.rendered);
                let end = rendered.source.len();
                if matches!(binding.origin, IdentifierOrigin::FromInput) {
                    rendered.from_input_ranges.push(start..end);
                }
            } else {
                rendered.source.push_str(ident);
            }
            continue;
        }

        rendered.source.push(ch);
        index += ch_len;
    }

    rendered
}

fn is_ident_start(ch: char) -> bool {
    ch == '_' || ch.is_ascii_alphabetic()
}

fn is_ident_continue(ch: char) -> bool {
    ch == '_' || ch.is_ascii_alphanumeric()
}

fn parse_expanded_expr(
    rendered: &RenderedTemplate,
    invocation_span: crate::frontend::ast::Span,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) -> Result<Spanned<Expr>, Diagnostic> {
    let wrapped =
        format!("fn __corex_macro_expand_tmp() {{ {} }}", rendered.source);
    let wrapper_prefix_len = "fn __corex_macro_expand_tmp() { ".len();
    let parsed = crate::frontend::parser::parse_source_file(&wrapped).map_err(
        |error| {
            Diagnostic::error("macro rule expansion parse failed")
                .with_label(DiagnosticLabel::primary(
                    FileSpan::new(file_id, invocation_span),
                    "expanded template is not a valid expression",
                ))
                .with_note(format!("{error}"))
        },
    )?;

    let Some(first_item) = parsed.ast.items.first() else {
        return Err(Diagnostic::error("macro rule expansion parse failed")
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation_span),
                "expanded template produced no parseable expression",
            )));
    };

    let Item::Function(function_decl) = &first_item.node else {
        return Err(Diagnostic::error("macro rule expansion parse failed")
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation_span),
                "expanded template did not parse as function wrapper",
            )));
    };

    let mut expr = if let Some(tail_expr) = &function_decl.node.body.tail_expr {
        tail_expr.as_ref().clone()
    } else if function_decl.node.body.statements.len() == 1 {
        match &function_decl.node.body.statements[0].node {
            Stmt::Expr { expr, .. } => expr.as_ref().clone(),
            _ => {
                return Err(Diagnostic::error(
                    "macro rule expansion did not produce an expression",
                )
                .with_label(DiagnosticLabel::primary(
                    FileSpan::new(file_id, invocation_span),
                    "expanded template produced a non-expression statement",
                )));
            }
        }
    } else {
        return Err(Diagnostic::error(
            "macro rule expansion did not produce an expression",
        )
        .with_label(DiagnosticLabel::primary(
            FileSpan::new(file_id, invocation_span),
            "expanded template produced multiple statements",
        )));
    };

    // v1 provenance bridge: keep macro call-site span on expanded root as
    // ExpandedFrom origin until full origin metadata lands in AST.
    apply_hygiene_to_expr(
        &mut expr,
        invocation_span,
        rendered,
        wrapper_prefix_len,
        file_id,
        provenance_map,
    );
    expr.span = invocation_span;
    Ok(expr)
}

fn parse_expanded_item(
    rendered: &RenderedTemplate,
    invocation_span: crate::frontend::ast::Span,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) -> Result<Spanned<Item>, Diagnostic> {
    let parsed = crate::frontend::parser::parse_source_file(&rendered.source)
        .map_err(|error| {
        Diagnostic::error("macro reflect expansion parse failed")
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation_span),
                "expanded reflect template is not a valid item",
            ))
            .with_note(format!("{error}"))
    })?;

    if parsed.ast.items.len() != 1 {
        return Err(Diagnostic::error(
            "macro reflect expansion did not produce exactly one item",
        )
        .with_label(DiagnosticLabel::primary(
            FileSpan::new(file_id, invocation_span),
            format!(
                "expected one generated item, found {}",
                parsed.ast.items.len()
            ),
        )));
    }

    let mut item = parsed.ast.items[0].clone();

    // v1 provenance bridge: keep macro call-site span on expanded root as
    // ExpandedFrom origin until full origin metadata lands in AST.
    apply_hygiene_to_item(&mut item, invocation_span, rendered, 0, file_id, provenance_map);
    item.span = invocation_span;
    Ok(item)
}

impl HygieneContext {
    fn new(
        invocation_span: crate::frontend::ast::Span,
        rendered: &RenderedTemplate,
        wrapper_offset: usize,
        file_id: FileId,
        provenance_map: ProvenanceMap,
    ) -> Self {
        let expansion_id =
            ((invocation_span.start as u64) << 32) ^ invocation_span.end as u64;
        let from_input_ranges = rendered
            .from_input_ranges
            .iter()
            .map(|range| {
                (range.start + wrapper_offset)..(range.end + wrapper_offset)
            })
            .collect::<Vec<_>>();

        Self {
            expansion_id,
            next_symbol_id: 0,
            next_scope_id: 0,
            scopes: vec![HygieneScope {
                id: 0,
                renames: BTreeMap::new(),
            }],
            from_input_ranges,
            provenance_map,
            file_id,
        }
    }

    fn push_scope(&mut self) {
        self.next_scope_id = self.next_scope_id.saturating_add(1);
        self.scopes.push(HygieneScope {
            id: self.next_scope_id,
            renames: BTreeMap::new(),
        });
    }

    fn pop_scope(&mut self) {
        if self.scopes.len() <= 1 {
            return;
        }
        if let Some(scope) = self.scopes.pop() {
            let _scope_id = scope.id;
        }
    }

    fn is_from_input_span(&self, span: crate::frontend::ast::Span) -> bool {
        self.from_input_ranges
            .iter()
            .any(|range| span.start >= range.start && span.end <= range.end)
    }

    fn origin_for_span(
        &self,
        span: crate::frontend::ast::Span,
    ) -> IdentifierOrigin {
        if self.is_from_input_span(span) {
            IdentifierOrigin::FromInput
        } else {
            IdentifierOrigin::Generated
        }
    }

    fn fresh_name(&mut self, base: &str) -> String {
        self.next_symbol_id = self.next_symbol_id.saturating_add(1);
        format!("{base}__h{}_{}", self.expansion_id, self.next_symbol_id)
    }

    fn declare_identifier(
        &mut self,
        name: &mut String,
        span: crate::frontend::ast::Span,
    ) {
        let origin = self.origin_for_span(span);
        if matches!(origin, IdentifierOrigin::FromInput) {
            return;
        }

        let original = name.clone();
        let fresh = self.fresh_name(&original);
        *name = fresh.clone();

        // Record provenance for the synthetic identifier
        self.provenance_map.insert(span, Provenance::SyntheticFor {
            purpose: SynthesisPurpose::HygieneRename,
            related_span: Some((self.file_id, span)),
        });

        if let Some(scope) = self.scopes.last_mut() {
            scope.renames.insert(original, fresh);
        }
    }

    fn rename_use(&self, name: &mut String, span: crate::frontend::ast::Span) {
        if matches!(self.origin_for_span(span), IdentifierOrigin::FromInput) {
            return;
        }

        for scope in self.scopes.iter().rev() {
            if let Some(fresh) = scope.renames.get(name) {
                *name = fresh.clone();
                return;
            }
        }
    }
}

fn apply_hygiene_to_expr(
    expr: &mut Spanned<Expr>,
    invocation_span: crate::frontend::ast::Span,
    rendered: &RenderedTemplate,
    wrapper_offset: usize,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) {
    let mut hygiene = HygieneContext::new(
        invocation_span,
        rendered,
        wrapper_offset,
        file_id,
        provenance_map.clone(),
    );
    hygienize_expr(expr, &mut hygiene);
    *provenance_map = hygiene.provenance_map;
}

fn apply_hygiene_to_item(
    item: &mut Spanned<Item>,
    invocation_span: crate::frontend::ast::Span,
    rendered: &RenderedTemplate,
    wrapper_offset: usize,
    file_id: FileId,
    provenance_map: &mut ProvenanceMap,
) {
    let mut hygiene = HygieneContext::new(
        invocation_span,
        rendered,
        wrapper_offset,
        file_id,
        provenance_map.clone(),
    );
    hygienize_item(item, &mut hygiene);
    *provenance_map = hygiene.provenance_map;
}

fn hygienize_item(item: &mut Spanned<Item>, hygiene: &mut HygieneContext) {
    if hygiene.is_from_input_span(item.span) {
        return;
    }

    match &mut item.node {
        Item::Function(function_decl) => {
            hygiene.declare_identifier(&mut function_decl.node.name, item.span);
            hygiene.push_scope();
            for param in &mut function_decl.node.params {
                hygiene.declare_identifier(&mut param.node.name, param.span);
            }
            hygienize_block(&mut function_decl.node.body, hygiene);
            hygiene.pop_scope();
        }
        Item::Struct(struct_decl) => {
            hygiene.declare_identifier(&mut struct_decl.node.name, item.span);
            for member in &mut struct_decl.node.members {
                match &mut member.node {
                    StructMember::Field(field) => {
                        hygiene.declare_identifier(
                            &mut field.node.name,
                            field.span,
                        );
                    }
                    StructMember::Init(init_decl) => {
                        hygiene.push_scope();
                        for param in &mut init_decl.node.params {
                            hygiene.declare_identifier(
                                &mut param.node.name,
                                param.span,
                            );
                        }
                        hygienize_block(&mut init_decl.node.body, hygiene);
                        hygiene.pop_scope();
                    }
                    StructMember::Function(function_decl) => {
                        hygiene.push_scope();
                        for param in &mut function_decl.node.params {
                            hygiene.declare_identifier(
                                &mut param.node.name,
                                param.span,
                            );
                        }
                        hygienize_block(&mut function_decl.node.body, hygiene);
                        hygiene.pop_scope();
                    }
                }
            }
        }
        Item::Enum(enum_decl) => {
            hygiene.declare_identifier(&mut enum_decl.node.name, item.span);
            for member in &mut enum_decl.node.members {
                if let EnumMember::Case(case_decl) = &mut member.node {
                    hygiene.declare_identifier(
                        &mut case_decl.node.name,
                        case_decl.span,
                    );
                }
            }
        }
        Item::Scope(scope_decl) => {
            hygiene.declare_identifier(&mut scope_decl.node.name, item.span);
        }
        Item::Protocol(protocol_decl) => {
            hygiene.declare_identifier(&mut protocol_decl.node.name, item.span);
        }
        Item::Macro(macro_decl) => {
            hygiene.declare_identifier(&mut macro_decl.node.name, item.span);
        }
        Item::Use(_) | Item::Impl(_) | Item::ExternBlock(_) => {}
    }
}

fn hygienize_block(block: &mut Block, hygiene: &mut HygieneContext) {
    for stmt in &mut block.statements {
        hygienize_stmt(stmt, hygiene);
    }
    if let Some(tail) = block.tail_expr.as_mut() {
        hygienize_expr(tail, hygiene);
    }
}

fn hygienize_clause_list(
    clauses: &mut ClauseList,
    hygiene: &mut HygieneContext,
) {
    for clause in &mut clauses.clauses {
        match &mut clause.node {
            Clause::Expr(expr) => hygienize_expr(expr, hygiene),
            Clause::LetBinding(binding) | Clause::VarBinding(binding) => {
                hygienize_expr(&mut binding.value, hygiene);
                hygienize_pattern(&mut binding.pattern, hygiene);
            }
        }
    }
}

fn hygienize_if_stmt(
    if_stmt: &mut Spanned<IfStmt>,
    hygiene: &mut HygieneContext,
) {
    if hygiene.is_from_input_span(if_stmt.span) {
        return;
    }

    hygiene.push_scope();
    hygienize_clause_list(&mut if_stmt.node.clauses, hygiene);
    hygienize_block(&mut if_stmt.node.then_branch, hygiene);
    hygiene.pop_scope();

    if let Some(else_branch) = if_stmt.node.else_branch.as_mut() {
        match else_branch {
            IfStmtElse::If(else_if) => hygienize_if_stmt(else_if, hygiene),
            IfStmtElse::Block(block) => {
                hygiene.push_scope();
                hygienize_block(block, hygiene);
                hygiene.pop_scope();
            }
        }
    }
}

fn hygienize_stmt(stmt: &mut Spanned<Stmt>, hygiene: &mut HygieneContext) {
    if hygiene.is_from_input_span(stmt.span) {
        return;
    }

    match &mut stmt.node {
        Stmt::If(if_stmt) => hygienize_if_stmt(if_stmt, hygiene),
        Stmt::Let(let_stmt) => {
            if let Some(value) = let_stmt.node.value.as_mut() {
                hygienize_expr(value, hygiene);
            }
            hygienize_pattern(&mut let_stmt.node.pattern, hygiene);
        }
        Stmt::Var(var_stmt) => {
            if let Some(value) = var_stmt.node.value.as_mut() {
                hygienize_expr(value, hygiene);
            }
            hygienize_pattern(&mut var_stmt.node.pattern, hygiene);
        }
        Stmt::Expr { expr, .. } => hygienize_expr(expr, hygiene),
        Stmt::Guard(guard_stmt) => {
            hygiene.push_scope();
            hygienize_clause_list(&mut guard_stmt.node.clauses, hygiene);
            hygienize_block(&mut guard_stmt.node.else_block, hygiene);
            hygiene.pop_scope();
        }
        Stmt::While(while_stmt) => {
            hygiene.push_scope();
            hygienize_clause_list(&mut while_stmt.node.clauses, hygiene);
            hygienize_block(&mut while_stmt.node.body, hygiene);
            hygiene.pop_scope();
        }
        Stmt::For(for_stmt) => {
            hygienize_expr(&mut for_stmt.node.iterator, hygiene);
            hygiene.push_scope();
            hygienize_pattern(&mut for_stmt.node.pattern, hygiene);
            hygienize_block(&mut for_stmt.node.body, hygiene);
            hygiene.pop_scope();
        }
        Stmt::Return(expr) => {
            if let Some(expr) = expr.as_mut() {
                hygienize_expr(expr, hygiene);
            }
        }
        Stmt::Break | Stmt::Continue => {}
    }
}

fn hygienize_pattern(
    pattern: &mut Spanned<Pattern>,
    hygiene: &mut HygieneContext,
) {
    if hygiene.is_from_input_span(pattern.span) {
        return;
    }

    match &mut pattern.node {
        Pattern::Identifier(name) => {
            hygiene.declare_identifier(name, pattern.span);
        }
        Pattern::Tuple(elements) => {
            for element in elements {
                hygienize_pattern(element, hygiene);
            }
        }
        Pattern::Variant { args, .. } => {
            for arg in args {
                hygienize_pattern(arg, hygiene);
            }
        }
        Pattern::Struct { fields, .. } => {
            for field in fields {
                if let Some(inner) = field.pattern.as_mut() {
                    hygienize_pattern(inner, hygiene);
                } else {
                    hygiene.declare_identifier(&mut field.name, pattern.span);
                }
            }
        }
        Pattern::Array { elements, rest } => {
            for element in elements {
                hygienize_pattern(element, hygiene);
            }
            if let Some(crate::frontend::ast::ArrayPatternRest::Bind(name)) =
                rest
            {
                hygiene.declare_identifier(name, pattern.span);
            }
        }
        Pattern::Wildcard
        | Pattern::IntegerLiteral(_)
        | Pattern::BooleanLiteral(_)
        | Pattern::CharLiteral(_)
        | Pattern::StringLiteral(_) => {}
    }
}

fn hygienize_expr(expr: &mut Spanned<Expr>, hygiene: &mut HygieneContext) {
    if hygiene.is_from_input_span(expr.span) {
        return;
    }

    match &mut expr.node {
        Expr::Identifier(name) => hygiene.rename_use(name, expr.span),
        Expr::Grouped(inner)
        | Expr::Try { expr: inner }
        | Expr::ForceUnwrap { expr: inner }
        | Expr::Spread { expr: inner }
        | Expr::Unary { expr: inner, .. } => {
            hygienize_expr(inner, hygiene);
        }
        Expr::StringLiteral(literal) => {
            for part in &mut literal.parts {
                if let crate::frontend::ast::StringPart::Interpolation(inner) =
                    part
                {
                    hygienize_expr(inner, hygiene);
                }
            }
        }
        Expr::ArrayLiteral(elements) => {
            for element in elements {
                match element {
                    crate::frontend::ast::ArrayElement::Expr(inner)
                    | crate::frontend::ast::ArrayElement::Spread(inner) => {
                        hygienize_expr(inner, hygiene);
                    }
                }
            }
        }
        Expr::StructLiteral { fields, .. } => {
            for field in fields {
                match field {
                    crate::frontend::ast::StructLiteralField::Named {
                        value,
                        ..
                    }
                    | crate::frontend::ast::StructLiteralField::Spread {
                        value,
                    } => hygienize_expr(value, hygiene),
                    crate::frontend::ast::StructLiteralField::Shorthand {
                        name,
                    } => {
                        hygiene.rename_use(name, expr.span);
                    }
                }
            }
        }
        Expr::Block(block) | Expr::UnsafeBlock(block) => {
            hygiene.push_scope();
            hygienize_block(block, hygiene);
            hygiene.pop_scope();
        }
        Expr::If {
            clauses,
            then_branch,
            else_branch,
        } => {
            hygiene.push_scope();
            hygienize_clause_list(clauses, hygiene);
            hygienize_block(then_branch, hygiene);
            hygiene.pop_scope();
            if let Some(else_branch) = else_branch.as_mut() {
                hygienize_expr(else_branch, hygiene);
            }
        }
        Expr::Match { subject, arms } => {
            hygienize_expr(subject, hygiene);
            for arm in arms {
                hygiene.push_scope();
                hygienize_pattern(&mut arm.node.pattern, hygiene);
                match &mut arm.node.body {
                    MatchArmBody::Expr(inner) => hygienize_expr(inner, hygiene),
                    MatchArmBody::Block(block) => {
                        hygienize_block(block, hygiene)
                    }
                }
                hygiene.pop_scope();
            }
        }
        Expr::Closure { params, body, .. } => {
            hygiene.push_scope();
            for param in params {
                hygiene.declare_identifier(&mut param.name, expr.span);
            }
            hygienize_block(body, hygiene);
            hygiene.pop_scope();
        }
        Expr::QualifiedMember { qualifier, .. } => {
            hygienize_expr(qualifier, hygiene)
        }
        Expr::Ternary {
            condition,
            then_expr,
            else_expr,
        } => {
            hygienize_expr(condition, hygiene);
            hygienize_expr(then_expr, hygiene);
            hygienize_expr(else_expr, hygiene);
        }
        Expr::Binary { lhs, rhs, .. } => {
            hygienize_expr(lhs, hygiene);
            hygienize_expr(rhs, hygiene);
        }
        Expr::Assignment { target, value, .. } => {
            hygienize_expr(target, hygiene);
            hygienize_expr(value, hygiene);
        }
        Expr::MemberAccess { base, .. }
        | Expr::OptionalMemberAccess { base, .. }
        | Expr::NamespaceAccess { base, .. } => hygienize_expr(base, hygiene),
        Expr::Call {
            callee,
            args,
            trailing_closure,
        } => {
            hygienize_expr(callee, hygiene);
            for arg in args {
                hygienize_expr(&mut arg.value, hygiene);
            }
            if let Some(trailing) = trailing_closure.as_mut() {
                hygienize_expr(trailing, hygiene);
            }
        }
        Expr::Index { base, index } | Expr::OptionalIndex { base, index } => {
            hygienize_expr(base, hygiene);
            hygienize_expr(index, hygiene);
        }
        Expr::Cast { expr: inner, .. } => hygienize_expr(inner, hygiene),
        Expr::Range { start, end, .. } => {
            if let Some(start) = start.as_mut() {
                hygienize_expr(start, hygiene);
            }
            if let Some(end) = end.as_mut() {
                hygienize_expr(end, hygiene);
            }
        }
        Expr::Macro { .. }
        | Expr::IntegerLiteral(_)
        | Expr::FloatLiteral(_)
        | Expr::CharLiteral(_)
        | Expr::BooleanLiteral(_)
        | Expr::SelfValue
        | Expr::SelfType
        | Expr::ShorthandMember { .. } => {}
    }
}

fn render_expr_to_source(expr: &Expr) -> Result<String, Diagnostic> {
    match expr {
        Expr::IntegerLiteral(value)
        | Expr::FloatLiteral(value)
        | Expr::CharLiteral(value)
        | Expr::Identifier(value) => Ok(value.clone()),
        Expr::BooleanLiteral(value) => Ok(value.to_string()),
        Expr::SelfValue => Ok("self".to_string()),
        Expr::SelfType => Ok("Self".to_string()),
        Expr::StringLiteral(literal) => {
            let mut output = String::from("\"");
            for part in &literal.parts {
                match part {
                    crate::frontend::ast::StringPart::Text(text) => {
                        output.push_str(
                            &text.replace('\\', "\\\\").replace('"', "\\\""),
                        );
                    }
                    crate::frontend::ast::StringPart::Interpolation(expr) => {
                        output.push_str("\\(");
                        output.push_str(&render_expr_to_source(&expr.node)?);
                        output.push(')');
                    }
                }
            }
            output.push('"');
            Ok(output)
        }
        Expr::Grouped(inner) => {
            Ok(format!("({})", render_expr_to_source(&inner.node)?))
        }
        Expr::Unary { op, expr } => {
            let op_text = match op {
                crate::frontend::ast::UnaryOp::Negate => "-",
                crate::frontend::ast::UnaryOp::Not => "!",
            };
            Ok(format!("{op_text}{}", render_expr_to_source(&expr.node)?))
        }
        Expr::Binary { op, lhs, rhs } => Ok(format!(
            "{} {} {}",
            render_expr_to_source(&lhs.node)?,
            render_binary_op(*op),
            render_expr_to_source(&rhs.node)?
        )),
        Expr::Ternary {
            condition,
            then_expr,
            else_expr,
        } => Ok(format!(
            "{} ? {} : {}",
            render_expr_to_source(&condition.node)?,
            render_expr_to_source(&then_expr.node)?,
            render_expr_to_source(&else_expr.node)?
        )),
        Expr::Assignment { op, target, value } => Ok(format!(
            "{} {} {}",
            render_expr_to_source(&target.node)?,
            render_assign_op(*op),
            render_expr_to_source(&value.node)?
        )),
        Expr::MemberAccess { base, member } => {
            Ok(format!("{}.{member}", render_expr_to_source(&base.node)?))
        }
        Expr::OptionalMemberAccess { base, member } => {
            Ok(format!("{}?.{member}", render_expr_to_source(&base.node)?))
        }
        Expr::NamespaceAccess { base, member, .. } => {
            Ok(format!("{}::{member}", render_expr_to_source(&base.node)?))
        }
        Expr::Call {
            callee,
            args,
            trailing_closure: _,
        } => {
            let rendered_args = args
                .iter()
                .map(|arg| render_expr_to_source(&arg.value.node))
                .collect::<Result<Vec<_>, _>>()?
                .join(", ");
            Ok(format!(
                "{}({rendered_args})",
                render_expr_to_source(&callee.node)?
            ))
        }
        Expr::Index { base, index } => Ok(format!(
            "{}[{}]",
            render_expr_to_source(&base.node)?,
            render_expr_to_source(&index.node)?
        )),
        Expr::OptionalIndex { base, index } => Ok(format!(
            "{}?[{}]",
            render_expr_to_source(&base.node)?,
            render_expr_to_source(&index.node)?
        )),
        Expr::ForceUnwrap { expr } => {
            Ok(format!("{}!", render_expr_to_source(&expr.node)?))
        }
        Expr::Try { expr } => {
            Ok(format!("try {}", render_expr_to_source(&expr.node)?))
        }
        Expr::Range {
            start,
            end,
            inclusive,
        } => {
            let op = if *inclusive { "..=" } else { ".." };
            let left = start
                .as_ref()
                .map(|expr| render_expr_to_source(&expr.node))
                .transpose()?
                .unwrap_or_default();
            let right = end
                .as_ref()
                .map(|expr| render_expr_to_source(&expr.node))
                .transpose()?
                .unwrap_or_default();
            Ok(format!("{left}{op}{right}"))
        }
        Expr::Macro { name, args } => match args {
            MacroExprArgs::Paren(args) => {
                let rendered = args
                    .iter()
                    .map(|arg| render_expr_to_source(&arg.value.node))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ");
                Ok(format!("@{name}({rendered})"))
            }
            MacroExprArgs::Braced(_) => Err(Diagnostic::error(
                "cannot render block-style macro invocation to source in v1",
            )),
        },
        Expr::ArrayLiteral(elements) => {
            let rendered = elements
                .iter()
                .map(|element| match element {
                    crate::frontend::ast::ArrayElement::Expr(expr) => {
                        render_expr_to_source(&expr.node)
                    }
                    crate::frontend::ast::ArrayElement::Spread(expr) => {
                        Ok(format!("..{}", render_expr_to_source(&expr.node)?))
                    }
                })
                .collect::<Result<Vec<_>, _>>()?
                .join(", ");
            Ok(format!("[{rendered}]"))
        }
        Expr::Spread { expr } => {
            Ok(format!("..{}", render_expr_to_source(&expr.node)?))
        }
        Expr::Cast {
            expr,
            ty,
            is_optional,
        } => Ok(format!(
            "{} as{} {}",
            render_expr_to_source(&expr.node)?,
            if *is_optional { "?" } else { "" },
            render_type_to_source(&ty.node)?
        )),
        _ => Err(Diagnostic::error(
            "unsupported expression form for v1 rule argument rendering",
        )),
    }
}

fn render_type_to_source(ty: &Type) -> Result<String, Diagnostic> {
    match ty {
        Type::Named { segments } => Ok(segments.join("::")),
        Type::SelfType => Ok("Self".to_string()),
        Type::Reference(inner) => {
            Ok(format!("&{}", render_type_to_source(&inner.node)?))
        }
        Type::MutableReference(inner) => {
            Ok(format!("&mut {}", render_type_to_source(&inner.node)?))
        }
        Type::ConstPointer(inner) => {
            Ok(format!("*{}", render_type_to_source(&inner.node)?))
        }
        Type::MutablePointer(inner) => {
            Ok(format!("*mut {}", render_type_to_source(&inner.node)?))
        }
        Type::Array(inner) => {
            Ok(format!("[{}]", render_type_to_source(&inner.node)?))
        }
        Type::Optional(inner) => {
            Ok(format!("{}?", render_type_to_source(&inner.node)?))
        }
        Type::Grouped(inner) => {
            Ok(format!("({})", render_type_to_source(&inner.node)?))
        }
        Type::GenericApplication { base, args } => {
            let rendered_args = args
                .iter()
                .map(|arg| render_type_to_source(&arg.node))
                .collect::<Result<Vec<_>, _>>()?
                .join(", ");
            Ok(format!(
                "{}<{rendered_args}>",
                render_type_to_source(&base.node)?
            ))
        }
        Type::Result { ok, err } => Ok(format!(
            "{}!{}",
            render_type_to_source(&ok.node)?,
            render_type_to_source(&err.node)?
        )),
    }
}

fn render_binary_op(op: crate::frontend::ast::BinaryOp) -> &'static str {
    match op {
        crate::frontend::ast::BinaryOp::LogicalOr => "||",
        crate::frontend::ast::BinaryOp::LogicalAnd => "&&",
        crate::frontend::ast::BinaryOp::NullCoalescing => "??",
        crate::frontend::ast::BinaryOp::BitOr => "|",
        crate::frontend::ast::BinaryOp::BitXor => "^",
        crate::frontend::ast::BinaryOp::BitAnd => "&",
        crate::frontend::ast::BinaryOp::Equal => "==",
        crate::frontend::ast::BinaryOp::NotEqual => "!=",
        crate::frontend::ast::BinaryOp::Less => "<",
        crate::frontend::ast::BinaryOp::LessEqual => "<=",
        crate::frontend::ast::BinaryOp::Greater => ">",
        crate::frontend::ast::BinaryOp::GreaterEqual => ">=",
        crate::frontend::ast::BinaryOp::ShiftLeft => "<<",
        crate::frontend::ast::BinaryOp::ShiftRight => ">>",
        crate::frontend::ast::BinaryOp::Add => "+",
        crate::frontend::ast::BinaryOp::Subtract => "-",
        crate::frontend::ast::BinaryOp::Multiply => "*",
        crate::frontend::ast::BinaryOp::Divide => "/",
        crate::frontend::ast::BinaryOp::Remainder => "%",
    }
}

fn render_assign_op(op: crate::frontend::ast::AssignOp) -> &'static str {
    match op {
        crate::frontend::ast::AssignOp::Assign => "=",
        crate::frontend::ast::AssignOp::AddAssign => "+=",
        crate::frontend::ast::AssignOp::SubAssign => "-=",
        crate::frontend::ast::AssignOp::MulAssign => "*=",
        crate::frontend::ast::AssignOp::DivAssign => "/=",
        crate::frontend::ast::AssignOp::RemAssign => "%=",
        crate::frontend::ast::AssignOp::BitXorAssign => "^=",
        crate::frontend::ast::AssignOp::BitOrAssign => "|=",
        crate::frontend::ast::AssignOp::BitAndAssign => "&=",
        crate::frontend::ast::AssignOp::ShlAssign => "<<=",
        crate::frontend::ast::AssignOp::ShrAssign => ">>=",
    }
}

