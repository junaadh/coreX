    #[test]
    fn rule_expansion_records_expanded_from_provenance() {
        let source = r#"
macro identity {
    rule(input: Expr) => { input };
}
fn main() { @identity(42); }
"#;
        let expanded = expand_source(source, 8);

        assert!(
            expanded.diagnostics.is_empty(),
            "unexpected diagnostics: {:?}",
            expanded.diagnostics.as_slice()
        );

        // The expanded expression should have provenance
        let main_expr_span = main_expr_span(&expanded);
        if let Some(prov) = expanded.provenance_map.get(main_expr_span) {
            match prov {
                Provenance::ExpandedFrom {
                    macro_name,
                    call_site_span,
                    definition_span,
                    ..
                } => {
                    assert_eq!(macro_name, "identity");
                    assert_eq!(*call_site_span, main_expr_span);
                    assert!(definition_span.is_some(), "definition span should be recorded");
                }
                _ => panic!("expected ExpandedFrom provenance, got {:?}", prov),
            }
        } else {
            panic!("no provenance recorded for expanded expression");
        }
    }

    #[test]
    fn nested_expansion_preserves_provenance_chain() {
        let source = r#"
macro inner {
    rule(input: Expr) => { input };
}
macro outer {
    rule(input: Expr) => { @inner(input) };
}
fn main() { @outer(99); }
"#;
        let expanded = expand_source(source, 8);

        assert!(
            expanded.diagnostics.is_empty(),
            "unexpected diagnostics: {:?}",
            expanded.diagnostics.as_slice()
        );

        // The final expanded expression should have provenance from the inner macro
        // because outer expands to @inner(input), and then inner expands that to just input
        let main_expr_span = main_expr_span(&expanded);
        if let Some(prov) = expanded.provenance_map.get(main_expr_span) {
            match prov {
                Provenance::ExpandedFrom { macro_name, .. } => {
                    assert_eq!(macro_name, "inner", "final expansion comes from inner macro");
                }
                _ => panic!("expected ExpandedFrom provenance, got {:?}", prov),
            }
        } else {
            panic!("no provenance recorded for nested expansion");
        }

        // We should also have provenance for the outer macro expansion
        // Check that we have multiple provenance entries showing the expansion chain
        assert!(expanded.provenance_map.len() >= 1,
                "should have at least one provenance entry");
    }

