/// Expanded parsed unit produced by [`expand_file`].
///
/// This extends `ParsedFile` with provenance tracking, which preserves
/// origin information through macro expansion. The provenance map allows
/// us to trace expanded code back to its macro call sites for better
/// diagnostics and tooling support.
#[derive(Debug, Clone)]
pub struct ExpandedFile {
    /// The file identifier
    pub file_id: FileId,
    /// The expanded AST (same structure as ParsedFile)
    pub ast: File,
    /// Diagnostics collected during expansion
    pub diagnostics: DiagnosticsBag,
    /// Provenance mapping for expanded nodes
    pub provenance_map: ProvenanceMap,
}

/// Macro expansion loop options.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ExpansionOptions {
    pub recursion_limit: usize,
}

impl Default for ExpansionOptions {
    fn default() -> Self {
        Self {
            recursion_limit: 64,
        }
    }
}

/// Clause kind for dispatch priority and selection.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MacroClauseKind {
    Reflect,
    Rule,
}

/// Clause input signature used for compatibility checks.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MacroInputSignature {
    Item,
    Expr,
    Stmt,
    Block,
    Type,
    Pattern,
    Tokens,
    MacroArgs,
}

/// One dispatchable macro clause.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct MacroClause {
    pub kind: MacroClauseKind,
    pub input_signature: MacroInputSignature,
    pub params: Vec<MacroParam>,
    pub body: MacroBlock,
}

/// One positional macro parameter used by rule execution.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct MacroParam {
    pub name: String,
    pub kind: MacroInputSignature,
}

/// One macro definition containing dispatchable clauses.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct MacroDefinition {
    pub name: String,
    pub clauses: Vec<MacroClause>,
    pub defining_file_id: FileId,
}

/// Invocation shape determines candidate input signature.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MacroInvocationShape {
    Attached,
    CallStyle,
    BlockStyle,
}

/// Normalized macro invocation used by dispatch.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct MacroInvocation {
    pub name: String,
    pub shape: MacroInvocationShape,
    pub span: crate::frontend::ast::Span,
}

/// Selected dispatch target for one invocation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SelectedMacroClause<'a> {
    pub definition: &'a MacroDefinition,
    pub clause: &'a MacroClause,
}

/// Name-indexed macro declaration table used during expansion/dispatch.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct MacroTable {
    declarations: BTreeMap<String, MacroDefinition>,
}

impl MacroTable {
    /// Creates an empty table.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Builds a macro table from parsed files.
    ///
    /// First declaration wins for duplicate names to keep behavior
    /// deterministic until duplicate-macro diagnostics are added.
    #[must_use]
    pub fn from_parsed_files(parsed_files: &[ParsedFile]) -> Self {
        let mut table = Self::new();
        for parsed in parsed_files {
            for item in &parsed.ast.items {
                if let Item::Macro(macro_decl) = &item.node {
                    table.insert(MacroDefinition::from_ast(
                        &macro_decl.node,
                        parsed.file_id,
                    ));
                }
            }
        }
        table
    }

    /// Inserts one macro definition keyed by its name.
    pub fn insert(
        &mut self,
        definition: MacroDefinition,
    ) -> Option<MacroDefinition> {
        let name = definition.name.clone();
        self.declarations.insert(name, definition)
    }

    /// Returns a macro definition by name.
    #[must_use]
    pub fn get(&self, name: &str) -> Option<&MacroDefinition> {
        self.declarations.get(name)
    }

    /// Returns the number of stored macros.
    #[must_use]
    pub fn len(&self) -> usize {
        self.declarations.len()
    }

    /// Returns true when the table has no declarations.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.declarations.is_empty()
    }
}

impl MacroDefinition {
    /// Builds a dispatchable macro definition from parsed AST declaration data.
    #[must_use]
    pub fn from_ast(declaration: &MacroDecl, file_id: FileId) -> Self {
        Self {
            name: declaration.name.clone(),
            clauses: declaration
                .clauses
                .iter()
                .map(|clause| MacroClause::from_ast(&clause.node))
                .collect(),
            defining_file_id: file_id,
        }
    }
}

impl MacroClause {
    /// Builds one dispatchable clause from parsed AST clause data.
    #[must_use]
    pub fn from_ast(clause: &AstMacroClause) -> Self {
        let params = clause
            .params
            .iter()
            .map(|param| MacroParam {
                name: param.node.name.clone(),
                kind: MacroInputSignature::from_ast(Some(param.node.kind)),
            })
            .collect::<Vec<_>>();

        Self {
            kind: MacroClauseKind::from_ast(clause.kind),
            input_signature: params
                .first()
                .map(|param| param.kind)
                .unwrap_or(MacroInputSignature::Tokens),
            params,
            body: clause.body.clone(),
        }
    }
}

impl MacroClauseKind {
    #[must_use]
    fn from_ast(kind: AstMacroClauseKind) -> Self {
        match kind {
            AstMacroClauseKind::Reflect => Self::Reflect,
            AstMacroClauseKind::Rule => Self::Rule,
        }
    }
}

impl MacroInputSignature {
    #[must_use]
    fn from_ast(kind: Option<AstMacroInputKind>) -> Self {
        match kind.unwrap_or(AstMacroInputKind::Tokens) {
            AstMacroInputKind::Item => Self::Item,
            AstMacroInputKind::Expr => Self::Expr,
            AstMacroInputKind::Stmt => Self::Stmt,
            AstMacroInputKind::Block => Self::Block,
            AstMacroInputKind::Type => Self::Type,
            AstMacroInputKind::Pattern => Self::Pattern,
            AstMacroInputKind::Tokens => Self::Tokens,
            AstMacroInputKind::MacroArgs => Self::MacroArgs,
        }
    }
}

impl MacroInvocation {
    /// Builds a dispatch invocation from an expression-form macro invocation.
    #[must_use]
    pub fn from_expr(expr: &Spanned<Expr>) -> Option<Self> {
        let Expr::Macro { name, args } = &expr.node else {
            return None;
        };
        let shape = match args {
            MacroExprArgs::Paren(_) => MacroInvocationShape::CallStyle,
            MacroExprArgs::Braced(_) => MacroInvocationShape::BlockStyle,
        };
        Some(Self {
            name: name.clone(),
            shape,
            span: expr.span,
        })
    }

    /// Builds an attached (item-position) invocation.
    #[must_use]
    pub fn attached(
        name: impl Into<String>,
        span: crate::frontend::ast::Span,
    ) -> Self {
        Self {
            name: name.into(),
            shape: MacroInvocationShape::Attached,
            span,
        }
    }
}

/// Selects the macro clause for one invocation without executing expansion.
///
/// Dispatch behavior:
/// 1. Resolve macro by name
/// 2. Determine invocation shape input (attached -> item, call -> expr, block -> tokens)
/// 3. Filter clauses by compatible input
/// 4. Prefer `Reflect` over `Rule`
/// 5. First compatible clause within that priority wins
///
/// # Errors
///
/// Returns a diagnostic when the macro is unknown or no clause is compatible.
pub fn dispatch_macro<'a>(
    macros: &'a MacroTable,
    invocation: &MacroInvocation,
    file_id: FileId,
) -> Result<SelectedMacroClause<'a>, Diagnostic> {
    let Some(definition) = macros.get(&invocation.name) else {
        return Err(unknown_macro_diagnostic(file_id, invocation));
    };

    let expected_input = invocation.shape.expected_input();
    let mut selected_reflect: Option<&MacroClause> = None;
    let mut selected_rule: Option<&MacroClause> = None;

    for clause in &definition.clauses {
        if clause.input_signature != expected_input {
            continue;
        }
        match clause.kind {
            MacroClauseKind::Reflect => {
                if selected_reflect.is_none() {
                    selected_reflect = Some(clause);
                }
            }
            MacroClauseKind::Rule => {
                if selected_rule.is_none() {
                    selected_rule = Some(clause);
                }
            }
        }
    }

    if let Some(clause) = selected_reflect.or(selected_rule) {
        // Validate that the selected clause is actually supported
        if !clause.input_signature.is_supported() {
            return Err(Diagnostic::error(format!(
                "macro `{}` clause has unsupported input kind: {}",
                definition.name,
                clause.input_signature.as_str()
            ))
            .with_label(DiagnosticLabel::primary(
                FileSpan::new(file_id, invocation.span),
                format!("{} invocation selected unsupported clause", invocation.shape.as_str()),
            ))
            .with_note(format!(
                "input kind {} is {}",
                clause.input_signature.as_str(),
                clause.input_signature.support_status()
            ))
            .with_help(
                "supported macro forms:\n\
                 - rule(Expr) for call-style @macro(...)\n\
                 - rule(Tokens) for block-style @macro{...}\n\
                 - reflect(Item) for attached @macro item"
            ));
        }

        // Validate clause kind and input signature compatibility
        match clause.kind {
            MacroClauseKind::Rule if !clause.input_signature.supports_rule() => {
                return Err(Diagnostic::error("rule clause has unsupported input kind")
                    .with_label(DiagnosticLabel::primary(
                        FileSpan::new(file_id, invocation.span),
                        format!("rule clauses do not support {}", clause.input_signature.as_str()),
                    ))
                    .with_note(format!(
                        "rule clauses support: Expr, Tokens (found {})",
                        clause.input_signature.as_str()
                    )))
            }
            MacroClauseKind::Reflect if !clause.input_signature.supports_reflect() => {
                return Err(Diagnostic::error("reflect clause has unsupported input kind")
                    .with_label(DiagnosticLabel::primary(
                        FileSpan::new(file_id, invocation.span),
                        format!("reflect clauses do not support {}", clause.input_signature.as_str()),
                    ))
                    .with_note(format!(
                        "reflect clauses support: Item (found {})",
                        clause.input_signature.as_str()
                    )))
            }
            _ => {}
        }

        return Ok(SelectedMacroClause { definition, clause });
    }

    Err(no_matching_clause_diagnostic(
        file_id,
        invocation,
        definition,
        expected_input,
    ))
}

impl MacroInvocationShape {
    #[must_use]
    fn expected_input(self) -> MacroInputSignature {
        match self {
            Self::Attached => MacroInputSignature::Item,
            Self::CallStyle => MacroInputSignature::Expr,
            Self::BlockStyle => MacroInputSignature::Tokens,
        }
    }

    #[must_use]
    fn as_str(self) -> &'static str {
        match self {
            Self::Attached => "attached",
            Self::CallStyle => "call-style",
            Self::BlockStyle => "block-style",
        }
    }
}

impl MacroInputSignature {
    #[must_use]
    fn as_str(self) -> &'static str {
        match self {
            Self::Item => "Item",
            Self::Expr => "Expr",
            Self::Stmt => "Stmt",
            Self::Block => "Block",
            Self::Type => "Type",
            Self::Pattern => "Pattern",
            Self::Tokens => "Tokens",
            Self::MacroArgs => "MacroArgs",
        }
    }

    /// Returns true if this input kind is currently supported for expansion.
    #[must_use]
    pub const fn is_supported(self) -> bool {
        matches!(self, Self::Item | Self::Expr | Self::Tokens)
    }

    /// Returns true if this input kind is supported for rule clauses.
    #[must_use]
    pub const fn supports_rule(self) -> bool {
        matches!(self, Self::Expr | Self::Tokens)
    }

    /// Returns true if this input kind is supported for reflect clauses.
    #[must_use]
    pub const fn supports_reflect(self) -> bool {
        matches!(self, Self::Item)
    }

    /// Human-readable description of support status.
    #[must_use]
    pub fn support_status(self) -> &'static str {
        match self {
            Self::Expr => "supported (rule clauses only)",
            Self::Tokens => "supported (rule clauses only)",
            Self::Item => "supported (reflect clauses only)",
            Self::Stmt | Self::Block | Self::Type | Self::Pattern => "not implemented",
            Self::MacroArgs => "declared but not implemented",
        }
    }
}

fn unknown_macro_diagnostic(
    file_id: FileId,
    invocation: &MacroInvocation,
) -> Diagnostic {
    Diagnostic::error("unknown macro").with_label(DiagnosticLabel::primary(
        FileSpan::new(file_id, invocation.span),
        format!("macro `{}` is not defined", invocation.name),
    ))
}

fn no_matching_clause_diagnostic(
    file_id: FileId,
    invocation: &MacroInvocation,
    definition: &MacroDefinition,
    expected_input: MacroInputSignature,
) -> Diagnostic {
    let available = definition
        .clauses
        .iter()
        .map(|clause| {
            format!("{:?}({})", clause.kind, clause.input_signature.as_str())
        })
        .collect::<Vec<_>>()
        .join(", ");

    Diagnostic::error("no matching macro clause")
        .with_label(DiagnosticLabel::primary(
            FileSpan::new(file_id, invocation.span),
            format!(
                "no compatible clause for {} invocation",
                invocation.shape.as_str()
            ),
        ))
        .with_note(format!(
            "expected input signature: {}",
            expected_input.as_str()
        ))
        .with_note(format!(
            "available clauses for `{}`: {}",
            definition.name,
            if available.is_empty() {
                "<none>".to_string()
            } else {
                available
            }
        ))
}

/// Expands one parsed file into an expanded AST.
///
/// Expansion is syntax-only (`AST -> AST`) and runs as a fixed-point loop.
/// `rule` clauses are executed through a local string-render/reparse model.
/// `reflect` clause execution remains intentionally unimplemented.
#[must_use]
pub fn expand_file(
    db: &crate::frontend::source::SourceDb,
    parsed: &ParsedFile,
    macros: &MacroTable,
    options: ExpansionOptions,
) -> ExpandedFile {
    expand_file_with_hook(db, parsed, macros, options, |invocation, macros, db, file_id, provenance_map| {
        placeholder_expand_macro(invocation, macros, db, file_id, provenance_map)
    })
}

/// Expands a parsed-file set as one project-level macro context.
///
/// The macro table is built from `parsed_files` so declarations in one file
/// can be used from another file in the same analysis session.
#[must_use]
pub fn expand_parsed_files(
    db: &crate::frontend::source::SourceDb,
    parsed_files: &[ParsedFile],
    options: ExpansionOptions,
) -> Vec<ExpandedFile> {
    let macros = MacroTable::from_parsed_files(parsed_files);
    parsed_files
        .iter()
        .map(|parsed| expand_file(db, parsed, &macros, options))
        .collect()
}

