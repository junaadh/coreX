    #[test]
    fn provenance_map_tracks_all_expansions() {
        let source = r#"
macro add_one {
    rule(input: Expr) => { input + 1 };
}
macro double {
    rule(input: Expr) => { input * 2 };
}
fn main() {
    @add_one(5);
    @double(10);
}
"#;
        let expanded = expand_source(source, 8);

        assert!(
            expanded.diagnostics.is_empty(),
            "unexpected diagnostics: {:?}",
            expanded.diagnostics.as_slice()
        );

        // Should have provenance entries for both macro expansions
        // The exact count depends on how many spans are recorded, but we should have at least 2
        assert!(expanded.provenance_map.len() >= 2,
                "expected at least 2 provenance entries, got {}",
                expanded.provenance_map.len());

        // Verify that we have ExpandedFrom provenance for our macros
        let mut found_add_one = false;
        let mut found_double = false;

        for (_span, prov) in expanded.provenance_map.iter() {
            if let Provenance::ExpandedFrom { macro_name, .. } = prov {
                if macro_name == "add_one" {
                    found_add_one = true;
                } else if macro_name == "double" {
                    found_double = true;
                }
            }
        }

        assert!(found_add_one, "should have provenance for add_one macro");
        assert!(found_double, "should have provenance for double macro");
    }

